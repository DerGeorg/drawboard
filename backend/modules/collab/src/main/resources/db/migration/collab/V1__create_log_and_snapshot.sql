-- The update log and the snapshots of the boards' drawings. Flyway runs this with default schema "collab", so names
-- are unqualified. The server never reads the drawing: data is an opaque Yjs update.
-- Structure only: types, NOT NULL, keys, indexes. Retention (keep the last 5 snapshots or 7 days) and the limits live
-- in the code - no CHECK, no computed default, no trigger.

CREATE TABLE board_update (
    id          uuid       PRIMARY KEY,               -- Uuid.generateV7(), generated by the application
    board_id    uuid       NOT NULL,                  -- id of a board of module "library" (no foreign key across schemas)
    seq         bigint     NOT NULL,                  -- per board, starting at 1, no gaps (assigned under the room's lock)
    data        bytea      NOT NULL,                  -- one Yjs update
    size        integer    NOT NULL,                  -- length of data in bytes (summed for the limits and the metric)
    author_id   uuid       NOT NULL,                  -- id of a user of module "users"
    created_at  timestamp  NOT NULL,                  -- UTC, application clock
    CONSTRAINT board_update_board_seq_key UNIQUE (board_id, seq)
);

CREATE TABLE board_snapshot (
    id          uuid       PRIMARY KEY,
    board_id    uuid       NOT NULL,
    up_to_seq   bigint     NOT NULL,                  -- contains at least every update up to and including this seq
    data        bytea      NOT NULL,                  -- the whole drawing as one Yjs update
    size        integer    NOT NULL,
    created_by  uuid       NOT NULL,
    created_at  timestamp  NOT NULL,
    CONSTRAINT board_snapshot_board_up_to_seq_key UNIQUE (board_id, up_to_seq)
);
