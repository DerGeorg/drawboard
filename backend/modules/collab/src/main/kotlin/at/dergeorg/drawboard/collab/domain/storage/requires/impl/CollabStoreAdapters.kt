import kotlinx.coroutines.flow.map
import kotlinx.coroutines.reactor.awaitSingle
import org.springframework.data.r2dbc.core.R2dbcEntityTemplate
import org.springframework.stereotype.Repository
import kotlin.uuid.Uuid

/** Implements the domain's [UpdateLog] port with Spring Data R2DBC. Rows are only ever inserted, read or deleted. */
@Repository
internal class UpdateLogAdapter(
    private val updates: UpdateR2dbcRepository,
    private val rows: UpdateRowR2dbcRepository,
    private val template: R2dbcEntityTemplate,
) : UpdateLog {

    /** A pure INSERT: the id is generated by the application, `save()` could not tell "new" from it. */
    @WithSpan
    override suspend fun append(update: LoggedUpdate) {
        template.insert(update.toEntity()).awaitSingle()
    }

    override fun readAfter(boardId: Uuid, afterSeq: Long): Flow<LoggedUpdate> =
        updates.findAllByBoardIdAndSeqGreaterThanOrderBySeqAsc(boardId, afterSeq).map { it.toDomain() }

    @WithSpan
    override suspend fun lastSeq(boardId: Uuid): Long? = rows.findFirstByBoardIdOrderBySeqDesc(boardId)?.seq

    @WithSpan
    override suspend fun countAfter(boardId: Uuid, afterSeq: Long): Long = updates.countByBoardIdAndSeqGreaterThan(boardId, afterSeq)

    @WithSpan
    override suspend fun sizeAfter(boardId: Uuid, afterSeq: Long): Long = updates.sumSizeAfter(boardId, afterSeq)

    @WithSpan
    override suspend fun totalSize(): Long = updates.sumSize()

    @WithSpan
    override suspend fun deleteUpTo(boardId: Uuid, seq: Long) {
        updates.deleteByBoardIdAndSeqLessThanEqual(boardId, seq)
    }

    @WithSpan
    override suspend fun deleteAll(boardId: Uuid) {
        updates.deleteByBoardId(boardId)
    }
}

/** Implements the domain's [SnapshotStore] port with Spring Data R2DBC. */
@Repository
internal class SnapshotStoreAdapter(
    private val snapshots: SnapshotR2dbcRepository,
    private val metas: SnapshotMetaR2dbcRepository,
    private val template: R2dbcEntityTemplate,
) : SnapshotStore {

    @WithSpan
    override suspend fun insert(snapshot: StoredSnapshot) {
        template.insert(snapshot.toEntity()).awaitSingle()
    }

    @WithSpan
    override suspend fun findById(boardId: Uuid, id: Uuid): StoredSnapshot? =
        snapshots.findById(id)?.takeIf { it.boardId == boardId }?.toDomain()

    @WithSpan
    override suspend fun findLatest(boardId: Uuid): StoredSnapshot? =
        snapshots.findFirstByBoardIdOrderByUpToSeqDesc(boardId)?.toDomain()

    @WithSpan
    override suspend fun listMeta(boardId: Uuid): List<SnapshotMeta> =
        metas.findAllByBoardIdOrderByUpToSeqDesc(boardId).map { it.toDomain() }

    @WithSpan
    override suspend fun totalSize(): Long = snapshots.sumSize()

    @WithSpan
    override suspend fun delete(ids: Collection<Uuid>) {
        if (ids.isNotEmpty()) snapshots.deleteAllById(ids)
    }

    @WithSpan
    override suspend fun deleteAll(boardId: Uuid) {
        snapshots.deleteByBoardId(boardId)
    }
}
