-- Estimation sessions (3.15, Fable 2026-11-19, E1-E24): Magic Estimation and Rotation over many cards at once. Seats, cards,
-- entries, reasons, moves and timers live only here, never in the Yjs document of the board (S7.6, E20). Structure only: types,
-- NOT NULL, keys, indexes. The caps, the state machine, the server clock, the visibility rules and the retention live in the code.

CREATE TABLE estimation_session (
    id                 uuid       PRIMARY KEY,   -- Uuid.generateV7(), generated by the application
    board_id           uuid       NOT NULL,      -- id of a board of module "library" (no foreign key across schemas)
    mode               text       NOT NULL,      -- MAGIC | ROTATION
    title              text       NOT NULL,
    deck_kind          text       NOT NULL,      -- FIBONACCI | TSHIRT | CUSTOM
    deck_values        text       NOT NULL,      -- the cards in deck order, separated by a line feed (never part of a value)
    anonymous          boolean    NOT NULL,
    placing_seconds    integer,                  -- MAGIC only; the settings are fixed at creation (E1)
    moving_seconds     integer,                  -- MAGIC only
    mark_threshold     integer,                  -- MAGIC only
    rounds             integer,                  -- ROTATION only
    round_seconds      integer,                  -- ROTATION only
    advance_when_done  boolean,                  -- ROTATION only
    state              text       NOT NULL,      -- LOBBY | PLACING | MOVING | ROTATING | REVIEW | DONE | CANCELLED
    round              integer    NOT NULL,      -- ROTATION: the current (from REVIEW: the last) round, from 0; MAGIC: 0
    phase_ends_at      timestamp,                -- deadline of the running phase (UTC, application clock); null outside them
    moderator_id       uuid       NOT NULL,      -- id of a user of module "users"
    moderator_name     text       NOT NULL,      -- display name as it was at creation
    item_count         integer    NOT NULL,
    created_at         timestamp  NOT NULL,
    started_at         timestamp,
    closed_at          timestamp,                -- when it became DONE or CANCELLED
    last_activity_at   timestamp  NOT NULL,      -- last write or transition: the idle cancel counts from here (E22)
    reduced_at         timestamp,                -- when the retention purge reduced it to numbers (E22)
    version            bigint     NOT NULL       -- ETag of getEstimationSession; every update names the version it read (E15)
);

CREATE INDEX estimation_session_board_state_idx ON estimation_session (board_id, state, created_at);
CREATE INDEX estimation_session_closed_idx ON estimation_session (state, closed_at) WHERE reduced_at IS NULL;

CREATE TABLE estimation_seat (
    id            uuid       PRIMARY KEY,        -- a random UUID of this session only (S1.10), never the user id
    session_id    uuid       NOT NULL REFERENCES estimation_session (id),
    kind          text       NOT NULL,           -- USER | GUEST
    principal_id  uuid       NOT NULL,           -- the user's own id, or the id of the guest session (the sub of the guest token)
    share_id      uuid,                          -- GUEST: the link the guest came through (revocation removes them, E11)
    display_name  text       NOT NULL,           -- as it was when the seat was taken
    position      integer    NOT NULL,           -- order of joining, from 1
    joined_at     timestamp  NOT NULL,
    seated        boolean    NOT NULL,           -- takes part: every seat in LOBBY, from the start only the picked ones
    slot          integer,                       -- secret place in the ring (E2); null in LOBBY, for watchers, and from REVIEW
                                                 -- when the session is anonymous or MAGIC (E5)
    removed       boolean    NOT NULL,           -- its link was revoked in a running phase (E11); never listed again
    CONSTRAINT estimation_seat_principal_key UNIQUE (session_id, kind, principal_id)
);

CREATE INDEX estimation_seat_share_idx ON estimation_seat (share_id) WHERE share_id IS NOT NULL;

CREATE TABLE estimation_item (
    id             uuid       PRIMARY KEY,
    session_id     uuid       NOT NULL REFERENCES estimation_session (id),
    position       integer    NOT NULL,          -- order given at creation, from 0
    ref_kind       text       NOT NULL,          -- STORY | KANBAN_CARD
    block_id       text       NOT NULL,          -- opaque id in the Yjs document, never checked (E20)
    card_id        text,                         -- KANBAN_CARD only
    ref_key        text       NOT NULL,          -- kind/block/card: each card at most once per session
    title          text       NOT NULL,          -- a copy, made at creation
    column_value   text,                         -- MAGIC: the deck value of its column
    move_count     integer    NOT NULL,          -- MAGIC: moves in MOVING
    marked         boolean    NOT NULL,          -- MAGIC: to be discussed; frozen when REVIEW starts
    touched        boolean    NOT NULL,          -- placed, moved or estimated by a seat removed for a revoked link (E11)
    decision       text,                         -- REVIEW/DONE: the moderator's decision
    overridden     boolean    NOT NULL,          -- the decision is not what the session produced (E13)
    CONSTRAINT estimation_item_ref_key UNIQUE (session_id, ref_key),
    CONSTRAINT estimation_item_position_key UNIQUE (session_id, position)
);

CREATE TABLE estimation_entry (
    id          uuid       PRIMARY KEY,         -- random (Uuid.random()): no time in the id
    session_id  uuid       NOT NULL REFERENCES estimation_session (id),
    item_id     uuid       NOT NULL REFERENCES estimation_item (id),
    seat_id     uuid,                            -- null from REVIEW on in anonymous sessions (E5) and after the retention purge
    round       integer    NOT NULL,
    estimate    text       NOT NULL,             -- a value of the deck
    reason      text,                            -- why the value changed; null when kept, for the first entry, after the purge
    kept        boolean    NOT NULL,
    shuffle     bigint     NOT NULL,             -- random key (SecureRandom): the order in REVIEW, never by round (E5)
    created_at  timestamp,                       -- null from REVIEW on in anonymous sessions and after the purge (no time to correlate)
    CONSTRAINT estimation_entry_round_key UNIQUE (item_id, round)
);

CREATE INDEX estimation_entry_session_idx ON estimation_entry (session_id);

CREATE TABLE estimation_move (
    id          uuid       PRIMARY KEY,         -- random (Uuid.random()): no time in the id
    session_id  uuid       NOT NULL REFERENCES estimation_session (id),
    item_id     uuid       NOT NULL REFERENCES estimation_item (id),
    seat_id     uuid,                            -- counts the limits and marks in MOVING; null from REVIEW on, always (E4)
    from_value  text,                            -- null when the card had no column
    to_value    text       NOT NULL,
    moved_at    timestamp,                       -- for the 10-second merge in MOVING; null from REVIEW on, always
    seq         bigint     NOT NULL,             -- order of the moves within the session (1, 2, ...): what REVIEW keeps
    CONSTRAINT estimation_move_seq_key UNIQUE (session_id, seq)
);

CREATE INDEX estimation_move_session_idx ON estimation_move (session_id, seat_id);
CREATE INDEX estimation_move_item_idx ON estimation_move (item_id);
