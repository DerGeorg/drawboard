-- Planning poker (S7.6): rounds, their participants and the votes. Flyway runs this with default schema "planning", so names
-- are unqualified. Structure only: types, NOT NULL, keys, indexes. The caps, the rules of the decks and the pruning live in the code.
-- Votes are only here and never in the Yjs document of the board: every client of the board could read them there.

CREATE TABLE poker_round (
    id                uuid       PRIMARY KEY,   -- Uuid.generateV7(), generated by the application
    board_id          uuid       NOT NULL,      -- id of a board of module "library" (no foreign key across schemas)
    story_block_id    text       NOT NULL,      -- opaque id of the story card in the Yjs document, never checked
    title             text       NOT NULL,
    deck_kind         text       NOT NULL,      -- FIBONACCI | TSHIRT | CUSTOM
    deck_values       text       NOT NULL,      -- the cards in the order the UI shows them, separated by a line feed (never part of a value)
    state             text       NOT NULL,      -- OPEN | REVEALED | CANCELLED
    facilitator_id    uuid       NOT NULL,      -- id of a user of module "users"
    facilitator_name  text       NOT NULL,      -- display name as it was when the round started
    created_at        timestamp  NOT NULL,      -- UTC, application clock
    closed_at         timestamp,                -- when it was revealed or cancelled
    revealed_at       timestamp,
    version           bigint     NOT NULL       -- ETag of getPokerRound, see PlanningService for what raises it
);

CREATE INDEX poker_round_board_state_idx ON poker_round (board_id, state, created_at);
CREATE UNIQUE INDEX poker_round_open_story_key ON poker_round (board_id, story_block_id) WHERE state = 'OPEN';

CREATE TABLE poker_participant (
    id            uuid       PRIMARY KEY,
    round_id      uuid       NOT NULL REFERENCES poker_round (id),
    kind          text       NOT NULL,          -- USER | GUEST
    principal_id  uuid       NOT NULL,          -- the user's own id, or the id of the guest session (the sub of the guest token)
    share_id      uuid,                         -- GUEST: the link the guest came through (revocation removes them)
    display_name  text       NOT NULL,          -- as it was when the participant joined
    position      integer    NOT NULL,          -- order of joining, from 1
    vote          text,                         -- a value of the deck; null = joined but not voted (and after a cancel)
    joined_at     timestamp  NOT NULL,
    CONSTRAINT poker_participant_principal_key UNIQUE (round_id, kind, principal_id)
);

CREATE INDEX poker_participant_share_idx ON poker_participant (share_id) WHERE share_id IS NOT NULL;
