-- The installed plugins, the files of their bundles and the storage they keep per board (S3). Flyway runs this with
-- default schema "plugins", so names are unqualified.
-- Structure only: types, NOT NULL, keys, indexes. The upload rules, the manifest rules and the limits live in the code.

CREATE TABLE plugin (
    id                      text       PRIMARY KEY,   -- the id of the manifest, e.g. org.example.timer
    name                    text       NOT NULL,
    version                 text       NOT NULL,
    description             text,
    enabled                 boolean    NOT NULL,
    installed_at            timestamp  NOT NULL,      -- UTC, application clock
    installed_by            uuid       NOT NULL,      -- id of a user of module "users" (no foreign key across schemas)
    bundle_sha256           text       NOT NULL,      -- of the uploaded ZIP: part of the immutable asset path
    bundle_sha384           text       NOT NULL,      -- of the uploaded ZIP: the checksum shown to the admin and audited
    entry                   text       NOT NULL,      -- path of the ES module inside the bundle
    integrity               text       NOT NULL,      -- sha384-<base64> of the entry module (SRI)
    block_types             text       NOT NULL,      -- JSON list, from the manifest
    requested_capabilities  text       NOT NULL,      -- JSON list, from the manifest
    granted_capabilities    text       NOT NULL,      -- JSON list, set by the admin
    revision                bigint     NOT NULL       -- optimistic lock (Spring Data @Version)
);

-- The entry list of an install: one row per file of the bundle. A request is resolved by an exact match of
-- (plugin_id, bundle_sha256, path) - never by joining a URL path onto a directory (S3.5).
CREATE TABLE plugin_file (
    id             uuid    PRIMARY KEY,               -- Uuid.generateV7(), generated by the application
    plugin_id      text    NOT NULL,
    bundle_sha256  text    NOT NULL,
    path           text    NOT NULL,
    media_type     text    NOT NULL,
    size           bigint  NOT NULL,
    data           bytea   NOT NULL,
    CONSTRAINT plugin_file_path_key UNIQUE (plugin_id, bundle_sha256, path)
);

-- The key-value object of a plugin on a board (S3.8): opaque JSON, at most 1 MB (checked in the code).
CREATE TABLE plugin_storage (
    id          uuid       PRIMARY KEY,
    board_id    uuid       NOT NULL,                  -- id of a board of module "library"
    plugin_id   text       NOT NULL,
    data        text       NOT NULL,
    version     bigint     NOT NULL,                  -- raised by every write; 0 = never written (no row)
    updated_at  timestamp  NOT NULL,
    CONSTRAINT plugin_storage_board_plugin_key UNIQUE (board_id, plugin_id)
);

CREATE INDEX plugin_storage_plugin_idx ON plugin_storage (plugin_id);
