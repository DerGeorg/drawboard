package at.dergeorg.drawboard.files.domain.files.requires.impl

import at.dergeorg.drawboard.files.domain.files.model.Conversion
import at.dergeorg.drawboard.files.domain.files.model.FileKind
import at.dergeorg.drawboard.files.domain.files.model.StoredFile
import org.springframework.data.annotation.Id
import org.springframework.data.annotation.Version
import org.springframework.data.relational.core.mapping.Table
import kotlin.time.Instant
import kotlin.uuid.Uuid

/** Row of `files.board_file`. Only used inside requires/impl; the domain sees [StoredFile]. */
@Table(schema = "files", name = "board_file")
internal data class FileEntity(
    @Id val id: Uuid,
    val boardId: Uuid,
    val name: String,
    val mediaType: String,
    val kind: String,
    val size: Long,
    val createdAt: Instant,
    val createdBy: Uuid,
    val conversion: String,
    val pageCount: Int?,
    val width: Int?,
    val height: Int?,
    val thumbnailMediaType: String?,
    val pdfSize: Long?,
    /** Optimistic lock; `null` also marks a new row (the id is generated by the application, see BoardEntity). */
    @Version val version: Long? = null,
)

internal fun FileEntity.toDomain() = StoredFile(
    id = id,
    boardId = boardId,
    name = name,
    mediaType = mediaType,
    kind = FileKind.valueOf(kind),
    size = size,
    createdAt = createdAt,
    createdBy = createdBy,
    conversion = Conversion.valueOf(conversion),
    pageCount = pageCount,
    width = width,
    height = height,
    thumbnailMediaType = thumbnailMediaType,
    pdfSize = pdfSize,
    version = version,
)

internal fun StoredFile.toEntity(version: Long?) = FileEntity(
    id = id,
    boardId = boardId,
    name = name,
    mediaType = mediaType,
    kind = kind.name,
    size = size,
    createdAt = createdAt,
    createdBy = createdBy,
    conversion = conversion.name,
    pageCount = pageCount,
    width = width,
    height = height,
    thumbnailMediaType = thumbnailMediaType,
    pdfSize = pdfSize,
    version = version,
)
