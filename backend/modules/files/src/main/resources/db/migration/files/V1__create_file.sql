-- Metadata of the files uploaded to boards (S4). The bytes live in the storage port (filesystem volume), under the
-- file's id - never under the name. Flyway runs this with default schema "files", so names are unqualified.
-- Structure only: types, NOT NULL, keys, indexes. Limits, quotas and the type allowlist live in the code.

CREATE TABLE board_file (
    id                    uuid       PRIMARY KEY,   -- Uuid.generateV7(), generated by the application; also the stored name
    board_id              uuid       NOT NULL,      -- id of a board of module "library" (no foreign key across schemas)
    name                  text       NOT NULL,      -- sanitised original name; display and Content-Disposition only
    media_type            text       NOT NULL,      -- detected from the content
    kind                  text       NOT NULL,      -- IMAGE | VIDEO | PDF | DOCUMENT
    size                  bigint     NOT NULL,      -- bytes of the original as stored
    created_at            timestamp  NOT NULL,      -- UTC, application clock
    created_by            uuid       NOT NULL,      -- id of a user of module "users"
    conversion            text       NOT NULL,      -- NONE | PENDING | DONE | FAILED
    page_count            integer,
    width                 integer,
    height                integer,
    thumbnail_media_type  text,                     -- null = no thumbnail variant
    pdf_size              bigint,                   -- null = no converted PDF
    version               bigint     NOT NULL       -- optimistic lock (Spring Data @Version)
);

-- "The files of a board", newest first; the count and the sum of the quota.
CREATE INDEX board_file_board_idx ON board_file (board_id, created_at, id);
-- The quota of a user.
CREATE INDEX board_file_created_by_idx ON board_file (created_by);
-- The conversions that were interrupted by a restart.
CREATE INDEX board_file_conversion_idx ON board_file (conversion);
