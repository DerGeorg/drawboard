-- Audit log: one row per DomainEvent, written in the same transaction as the change it describes.
-- Flyway runs this with default schema "auditing" (created by Flyway), so names are unqualified.
--
-- Structure only - no function, no trigger, no CHECK, no computed default. Append-only is enforced by the
-- auditing module itself: its store can only insert and read (ArchUnit checks it), no other module reaches the
-- table. Retention drops whole time partitions later (DDL), never single rows.

CREATE TABLE audit_event (
    id           uuid       PRIMARY KEY,   -- Uuid.generateV7(), generated by the application (time-ordered)
    occurred_at  timestamp  NOT NULL,      -- UTC, application clock
    event_type   text       NOT NULL,      -- board.task.completed
    module       text       NOT NULL,      -- board
    entity_type  text       NOT NULL,      -- task
    entity_id    text       NOT NULL,      -- text: fits uuid, numbers and natural keys; no foreign key
    action       text       NOT NULL,      -- AuditAction (Kotlin enum, validated by the application)
    actor_type   text       NOT NULL,      -- ActorType: USER, SYSTEM, ANONYMOUS
    actor_id     text,                     -- token subject (Keycloak user id) or job name
    request_id   text,                     -- X-Request-Id, default = trace id
    trace_id     text,                     -- W3C trace id
    changes      jsonb,                    -- [{"path":"done","before":false,"after":true}]
    details_type text,                     -- logical name of the details, also in details."@type"
    details      jsonb                     -- typed, domain-specific payload
);

-- The typical questions, newest first:
CREATE INDEX audit_event_entity_idx  ON audit_event (entity_type, entity_id, occurred_at DESC); -- history / latest per entity
CREATE INDEX audit_event_actor_idx   ON audit_event (actor_id, occurred_at DESC) WHERE actor_id IS NOT NULL;
CREATE INDEX audit_event_type_idx    ON audit_event (event_type, occurred_at DESC);
CREATE INDEX audit_event_request_idx ON audit_event (request_id) WHERE request_id IS NOT NULL;  -- everything one request did
CREATE INDEX audit_event_trace_idx   ON audit_event (trace_id) WHERE trace_id IS NOT NULL;
CREATE INDEX audit_event_time_brin   ON audit_event USING brin (occurred_at);                   -- time ranges, tiny index
