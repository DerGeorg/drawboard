package at.dergeorg.drawboard.library.domain.boards.requires.impl

import at.dergeorg.drawboard.library.domain.boards.model.Board
import org.springframework.data.annotation.Id
import org.springframework.data.annotation.Version
import org.springframework.data.relational.core.mapping.Table
import kotlin.time.Instant
import kotlin.uuid.Uuid

/** Row of `library.board`. Only used inside requires/impl; the domain sees [Board]. */
@Table(schema = "library", name = "board")
internal data class BoardEntity(
    @Id val id: Uuid,
    val title: String,
    val ownerId: Uuid,
    val createdAt: Instant,
    val updatedAt: Instant,
    val folderId: Uuid?,
    val deletedAt: Instant?,
    /**
     * Optimistic lock, checked and raised by `save()`. `null` also marks the entity as new: the id is generated by
     * the application (UUIDv7), so Spring Data cannot tell "new" from the id - with a null version, `save()` INSERTs.
     */
    @Version val version: Long? = null,
)

internal fun BoardEntity.toDomain() = Board(
    id = id,
    title = title,
    ownerId = ownerId,
    createdAt = createdAt,
    updatedAt = updatedAt,
    version = checkNotNull(version) { "board $id has no version" },
    folderId = folderId,
    deletedAt = deletedAt,
)

/** [version] null = a new board (INSERT), otherwise the version the change is based on. */
internal fun Board.toEntity(version: Long?) = BoardEntity(
    id = id,
    title = title,
    ownerId = ownerId,
    createdAt = createdAt,
    updatedAt = updatedAt,
    folderId = folderId,
    deletedAt = deletedAt,
    version = version,
)
