-- Rights of principals on boards and folders (user, group, or a user remembered through a share link).
-- Structure only: the strongest-role rule, inheritance and "never OWNER" live in the code.

CREATE TABLE grant_entry (
    id              uuid       PRIMARY KEY,              -- Uuid.generateV7(), generated by the application
    resource_kind   text       NOT NULL,                 -- BOARD | FOLDER
    resource_id     uuid       NOT NULL,                 -- board.id or folder.id
    principal_kind  text       NOT NULL,                 -- USER | GROUP | LINK_USER
    principal       text       NOT NULL,                 -- user id (USER, LINK_USER) or group name (GROUP)
    role            text       NOT NULL,                 -- EDITOR | COMMENTER | VIEWER
    link_id         uuid,                                -- the share link of a LINK_USER grant
    created_at      timestamp  NOT NULL,                 -- UTC, application clock
    updated_at      timestamp  NOT NULL,
    CONSTRAINT grant_entry_principal_key UNIQUE (resource_kind, resource_id, principal_kind, principal)
);

-- "Shared with me": by principal.
CREATE INDEX grant_entry_principal_idx ON grant_entry (principal_kind, principal);
CREATE INDEX grant_entry_link_idx ON grant_entry (link_id);
