-- Metadata of the boards (the drawing itself is not stored here). Flyway runs this with default schema "library"
-- (created by Flyway), so names are unqualified.
-- Structure only: types, NOT NULL, keys, indexes. Rules (title not blank, at most 200 characters, who may do what)
-- live in the contract and in LibraryService - no CHECK, no computed default.

CREATE TABLE board (
    id          uuid       PRIMARY KEY,               -- Uuid.generateV7(), generated by the application
    title       text       NOT NULL,
    owner_id    uuid       NOT NULL,                  -- id of a user of module "users" (no foreign key across schemas)
    created_at  timestamp  NOT NULL,                  -- UTC, application clock
    updated_at  timestamp  NOT NULL,                  -- UTC, application clock
    version     bigint     NOT NULL                   -- optimistic lock (Spring Data @Version)
);

-- "My boards": WHERE owner_id = ? ORDER BY updated_at DESC, id DESC.
CREATE INDEX board_owner_updated_idx ON board (owner_id, updated_at, id);
