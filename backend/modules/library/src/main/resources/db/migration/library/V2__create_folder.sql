-- Folders of the personal spaces; boards get a folder and a trash marker. Structure only (no CHECK, no default).
-- A parent_id / folder_id of NULL is the root of the owner's space. deleted_at is set while an item is in the trash.

CREATE TABLE folder (
    id          uuid       PRIMARY KEY,               -- Uuid.generateV7(), generated by the application
    name        text       NOT NULL,
    owner_id    uuid       NOT NULL,                  -- id of a user of module "users" (no foreign key across schemas)
    parent_id   uuid,                                 -- another folder of the same owner, NULL = root
    created_at  timestamp  NOT NULL,                  -- UTC, application clock
    updated_at  timestamp  NOT NULL,
    deleted_at  timestamp,                            -- NULL = not in the trash
    version     bigint     NOT NULL                   -- optimistic lock (Spring Data @Version)
);

CREATE INDEX folder_owner_idx ON folder (owner_id);
CREATE INDEX folder_deleted_idx ON folder (deleted_at);

ALTER TABLE board ADD COLUMN folder_id uuid;
ALTER TABLE board ADD COLUMN deleted_at timestamp;

CREATE INDEX board_folder_idx ON board (folder_id);
CREATE INDEX board_deleted_idx ON board (deleted_at);
