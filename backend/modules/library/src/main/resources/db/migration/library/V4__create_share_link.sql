-- Share links to a board or folder (S1). The token is never stored, only its sha256 (lowercase hex); the password only
-- as an Argon2 hash. Structure only: roles, audiences and the usable-state rules live in the code.

CREATE TABLE share_link (
    id             uuid       PRIMARY KEY,              -- Uuid.generateV7(), generated by the application
    resource_kind  text       NOT NULL,                 -- BOARD | FOLDER
    resource_id    uuid       NOT NULL,                 -- board.id or folder.id
    role           text       NOT NULL,                 -- EDITOR | COMMENTER | VIEWER
    audience       text       NOT NULL,                 -- SIGNED_IN | GUESTS
    token_hash     text       NOT NULL,                 -- sha256(token), lowercase hex
    password_hash  text,                                -- Argon2 hash, NULL = no password
    expires_at     timestamp,                           -- UTC, NULL = does not expire
    revoked_at     timestamp,                           -- UTC, NULL = not revoked
    use_count      bigint     NOT NULL,                 -- successful exchanges
    created_at     timestamp  NOT NULL,                 -- UTC, application clock
    created_by     uuid       NOT NULL,                 -- id of a user of module "users"
    CONSTRAINT share_link_token_hash_key UNIQUE (token_hash)
);

CREATE INDEX share_link_resource_idx ON share_link (resource_kind, resource_id);
