-- Profiles of the users who signed in. Flyway runs this with default schema "users" (created by Flyway).
-- Structure only; lengths and formats of the claims are the OIDC provider's business, not the table's.

CREATE TABLE user_profile (
    id              uuid       PRIMARY KEY,      -- Uuid.generateV7(), generated by the application
    issuer          text       NOT NULL,         -- claim iss of the access token
    subject         text       NOT NULL,         -- claim sub of the access token
    username        text       NOT NULL,         -- claim configured by OIDC_CLAIM_USERNAME
    display_name    text,                        -- claim name
    email           text,                        -- claim email, only stored when email_verified is true
    groups          text[]     NOT NULL,         -- claim configured by OIDC_CLAIM_GROUPS; display only, decisions use the current token
    first_login_at  timestamp  NOT NULL,         -- UTC, application clock
    last_login_at   timestamp  NOT NULL,         -- UTC, application clock
    version         bigint     NOT NULL,         -- optimistic lock (Spring Data @Version)
    CONSTRAINT user_profile_login_key UNIQUE (issuer, subject)
);
